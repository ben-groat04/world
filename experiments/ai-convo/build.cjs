// node build.cjs -> workflow/dist/<name>.js: each thin wrapper in workflow/ with its //@include line replaced by that file
// (Workflow scripts must be self-contained and cannot import.) Launch the files in workflow/dist/; never edit them.
const fs = require('fs'), path = require('path'), dir = path.join(__dirname, 'workflow'), out = path.join(dir, 'dist')
fs.mkdirSync(out, { recursive: true })
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.js'))) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8').replace(/^\/\/@include (.+)$/m, (_, p) => fs.readFileSync(path.join(dir, p.trim()), 'utf8'))
  if (/Math\.random|Date\.now|new Date\(\)|\bimport\b|\brequire\(/.test(src.replace(/\/\/.*$/gm, ''))) throw new Error(`${f}: non-deterministic API or import`)
  fs.writeFileSync(path.join(out, f), src + `\n// GENERATED by build.cjs from workflow/${f}; do not edit\n`); console.log('wrote', path.join(out, f), fs.statSync(path.join(out, f)).size, 'bytes')
}
